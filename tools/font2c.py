#!/usr/bin/env python3
"""LiteKern X - build step: the GUI font atlas -> C (kernel/text.h).

Usage: python3 tools/font2c.py assets/fonts/ui-font.json OUT.c
       python3 tools/font2c.py --bin assets/fonts/clock-font.json OUT.lkxf
                (its one face as a file the kernel loads: see kernel/lockscreen.c)

Reads ui-font.json and ui-font.png (made by tools/font-rasterize.py) and
writes each face's metrics, glyph table and 8-bit coverage, one array per
face. Standard library only (tools/lkx_png.py reads the PNG).
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lkx_png import read_rgba  # noqa: E402


def main():
    if len(sys.argv) == 4 and sys.argv[1] == "--bin":
        return write_bin(sys.argv[2], sys.argv[3])
    if len(sys.argv) != 3:
        sys.exit("usage: font2c.py FONT.json OUT.c | --bin FONT.json OUT.lkxf")
    meta = json.load(open(sys.argv[1], encoding="utf-8"))
    png = sys.argv[1][:-5] + ".png"
    w, h, px = read_rgba(png)
    out = [f'/* Generated by tools/font2c.py from {os.path.basename(sys.argv[1])[:-5]}.*. Do not edit. */',
           '#include "kernel/text.h"', ""]
    faces = []
    for fi, face in enumerate(meta["faces"]):
        cov, glyphs = [], []
        for g in face["glyphs"]:
            off = len(cov)
            for y in range(g["h"]):
                for x in range(g["w"]):
                    cov.append(px[g["y"] + y][g["x"] + x][0])
            glyphs.append(f'    {{ {g["w"]}, {g["h"]}, {g["xoff"]}, {g["yoff"]}, {g["adv64"]}, {off} }},')
        body = ",\n".join("    " + ", ".join(str(v) for v in cov[k:k + 24]) for k in range(0, len(cov), 24))
        out.append(f"static const uint8_t cov_{fi}[{max(len(cov), 1)}] = {{\n{body or '    0'}\n}};")
        out.append(f"static const struct text_glyph glyphs_{fi}[{len(glyphs)}] = {{\n" + "\n".join(glyphs) + "\n};")
        faces.append(f'    {{ "{face["name"]}", {face["size"]}, {face["ascent"]}, {face["descent"]}, '
                     f'glyphs_{fi}, cov_{fi} }},')
    out.append("const struct text_face text_faces[TEXT_FACES] = {\n" + "\n".join(faces) + "\n};")
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"font2c: {len(faces)} faces -> {sys.argv[2]}")


def write_bin(json_path, out_path):
    """One face as a file: "LKXF", then little-endian u16 size, ascent,
    descent and glyph count; each glyph as u8 w, h, s8 xoff, yoff, u16
    adv64, u32 coverage offset; then the 8-bit coverage."""
    import struct
    meta = json.load(open(json_path, encoding="utf-8"))
    w, h, px = read_rgba(json_path[:-5] + ".png")
    face = meta["faces"][0]
    cov, table = bytearray(), bytearray()
    for g in face["glyphs"]:
        table += struct.pack("<BBbbHI", g["w"], g["h"], g["xoff"], g["yoff"], g["adv64"], len(cov))
        for y in range(g["h"]):
            for x in range(g["w"]):
                cov.append(px[g["y"] + y][g["x"] + x][0])
    head = b"LKXF" + struct.pack("<HHHH", face["size"], face["ascent"], face["descent"], len(face["glyphs"]))
    with open(out_path, "wb") as f:
        f.write(head + table + cov)
    print(f"font2c: {face['name']} ({len(face['glyphs'])} glyphs, {len(cov) // 1024} KB) -> {out_path}")


if __name__ == "__main__":
    main()

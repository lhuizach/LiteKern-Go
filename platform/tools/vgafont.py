"""LiteKern X (Linux) - the 8x16 console font, taken from a VGA BIOS image.

On the EeePC the kernel version copies the video BIOS's own font; a Linux
program can't reach it, so the build takes the same kind of font from
QEMU's VGA BIOS (SeaBIOS's vgabios) and writes it as C.

Usage: python3 vgafont.py VGABIOS.bin OUT.c
"""
import sys

# 'A' in the standard IBM VGA 8x16 font.
A = bytes([0x00, 0x00, 0x10, 0x38, 0x6c, 0xc6, 0xc6, 0xfe, 0xc6, 0xc6, 0xc6, 0xc6, 0x00, 0x00, 0x00, 0x00])

data = open(sys.argv[1], "rb").read()
at = data.find(A)
while at >= 0:
    base = at - ord("A") * 16
    # glyph 0 is blank, and the font is 256 glyphs
    if base >= 0 and base + 4096 <= len(data) and data[base:base + 16] == bytes(16):
        break
    at = data.find(A, at + 1)
if at < 0:
    sys.exit("vgafont: no 8x16 font found in " + sys.argv[1])
font = data[base:base + 4096]
with open(sys.argv[2], "w") as f:
    f.write("/* Generated by platform/tools/vgafont.py from %s. */\n" % sys.argv[1])
    f.write("#include <stdint.h>\n\nconst uint8_t vga_font_8x16[4096] = {\n")
    for i in range(0, 4096, 16):
        f.write("    " + ", ".join("0x%02x" % b for b in font[i:i + 16]) + ",\n")
    f.write("};\n")
